def get_word_image(term, index=0):
    if not term:
        return CATEGORY_FALLBACKS[index % len(CATEGORY_FALLBACKS)]
    
    # Direct match
    if term in VOCAB_IMAGE_MAP:
        return VOCAB_IMAGE_MAP[term]
    
    # Substring match
    term_lower = term.lower()
    for k, v in VOCAB_IMAGE_MAP.items():
        if k.lower() in term_lower or term_lower in k.lower():
            return v
            
    # Deterministic hash to fallback
    h = sum(ord(c) for c in term)
    return CATEGORY_FALLBACKS[h % len(CATEGORY_FALLBACKS)]
